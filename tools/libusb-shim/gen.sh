# Generate x86-64 trampolines for every libusb export not hooked in shim.c.
set -e
CC=${CC:-gcc}
REAL=${1:-/usr/lib/$($CC -print-multiarch)/libusb-1.0.so.0}
nm -D --defined-only "$REAL" | awk '$2=="T"{print $3}' | sort > exports.txt
grep -oE '^(int|void) (libusb_[a-z_]+)\(|^HOOK1\((libusb_[a-z_]+)' shim.c | grep -oE 'libusb_[a-z_]+' | sort -u > hooked.txt
comm -23 exports.txt hooked.txt > forwarded.txt
{
  echo '	.text'
  i=0
  while read s; do
    printf '	.globl %s\n	.type %s,%%function\n%s:\n	jmp *shim_real+%d(%%rip)\n' "$s" "$s" "$s" $((i*8))
    i=$((i+1))
  done < forwarded.txt
  echo '	.section .note.GNU-stack,"",%progbits'
} > tramp.S
{
  echo '// generated by gen.sh'
  echo 'const char *const shim_names[] = {'
  sed 's/.*/\t"&",/' forwarded.txt
  echo '};'
  echo "const int shim_count = $(wc -l < forwarded.txt);"
} > names.c
